export const GLYPH_ROWS = 7;

/** Turns text into dot columns (each column is seven booleans), with one blank column between letters. */
export function textToColumns(text: string): boolean[][] {
  const columns: boolean[][] = [];
  for (const char of text.toLowerCase()) {
    const glyph = FONT[char] ?? FONT['?'];
    for (let x = 0; x < 5; x++) columns.push(glyph.map((row) => row[x] === '1'));
    columns.push(new Array(GLYPH_ROWS).fill(false));
  }
  return columns;
}
